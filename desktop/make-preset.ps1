# Generates the llama-server router preset (<root>\models.ini) and the launcher (<root>\start-hub.cmd) from elai.json.
# Re-run after editing elai.json. Model files must already exist (see get-models.ps1).
[CmdletBinding()]
param(
    [string]$Root,
    [string]$ModelsDir,
    [string]$OutFile,
    [string]$CmdFile,
    [switch]$AllowMissing,
    [switch]$Quiet
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot "elai-common.ps1")

$settings = Get-ElaiSettings -RootOverride $Root -ModelsDirOverride $ModelsDir
$r = $settings.resolved
$ini = if ($OutFile) { $OutFile } else { $r.PresetPath }
$cmd = if ($CmdFile) { $CmdFile } else { $r.StartCmd }
if (-not [System.IO.Path]::IsPathRooted($ini)) { $ini = Join-Path (Get-Location).Path $ini }
if (-not [System.IO.Path]::IsPathRooted($cmd)) { $cmd = Join-Path (Get-Location).Path $cmd }

function Get-Prop {
    param($Obj, [string]$Name, $Default = $null)
    if ($null -ne $Obj -and (Test-Prop $Obj $Name)) { return $Obj.$Name }
    return $Default
}

function Format-IniNumber {
    param($Value)
    # Invariant culture so 0.95 never becomes 0,95.
    return ([double]$Value).ToString([System.Globalization.CultureInfo]::InvariantCulture)
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("version = 1")
$lines.Add("; ELAI hub presets - generated by make-preset.ps1 from desktop\elai.json; edit elai.json and re-run instead of editing this file.")
$lines.Add("; One llama-server router serves every section below; clients pick a model by name (coder, planner).")
$lines.Add("")
$lines.Add("[*]")
$lines.Add("jinja = true")
$lines.Add("flash-attn = auto")
$lines.Add("cache-type-k = q8_0")
$lines.Add("cache-type-v = q8_0")
$lines.Add("batch-size = 2048")
$lines.Add("ubatch-size = 512")
$lines.Add("cache-ram = " + [int](Get-Prop $settings.router 'cacheRamMiB' 8192))
$lines.Add("")

$missing = @()
foreach ($name in (Get-ModelNames -Settings $settings)) {
    $m = $settings.models.$name
    $path = Find-ModelFile -FileName $m.file -ModelsDir $r.ModelsDir
    if (-not $path) {
        $missing += $m.file
        $path = Join-Path $r.ModelsDir $m.file
    }
    $slots = [int](Get-Prop $m 'slots' 1)
    $ctx = [int](Get-Prop $m 'ctx' 65536)

    $lines.Add("[$name]")
    $lines.Add("; " + [string](Get-Prop $m 'role' ''))
    $lines.Add("model = $path")
    if ((Get-Prop $m 'vision' $false) -and (Get-Prop $m 'mmproj' '')) {
        $mp = Find-ModelFile -FileName $m.mmproj -ModelsDir $r.ModelsDir
        if (-not $mp) { $missing += $m.mmproj; $mp = Join-Path $r.ModelsDir $m.mmproj }
        $lines.Add("mmproj = $mp")
    }
    $lines.Add("load-on-startup = " + $(if (Get-Prop $m 'loadOnStartup' $true) { "true" } else { "false" }))
    if (Get-Prop $m 'cpuMoe' $false) {
        $lines.Add("; all MoE expert weights stay in system RAM; attention/shared layers go to the GPU")
        $lines.Add("n-gpu-layers = 99")
        $lines.Add("cpu-moe = true")
    } else {
        $layers = [int](Get-Prop $m 'cpuMoeLayers' 0)
        if ($layers -gt 0) {
            $lines.Add("; experts of the first $layers layers stay in system RAM to free VRAM (raise if the model does not fit)")
            $lines.Add("n-cpu-moe = $layers")
        } else {
            $lines.Add("; n-gpu-layers is left to --fit (default on): everything on the GPU when it fits")
        }
    }
    $threads = [int](Get-Prop $m 'threads' 0)
    if ($threads -gt 0) { $lines.Add("threads = $threads") }
    $lines.Add("; total context shared by the slots: each of the $slots slots gets " + [int]($ctx / $slots) + " tokens")
    $lines.Add("ctx-size = $ctx")
    $lines.Add("parallel = $slots")
    if (Get-Prop $m 'reasoning' $false) {
        $lines.Add("; thinking goes to message.reasoning_content (OpenAI-style), not into the answer text")
        $lines.Add("reasoning-format = deepseek")
    }
    $sampling = Get-Prop $m 'sampling' $null
    if ($sampling) {
        foreach ($p in $sampling.PSObject.Properties) {
            $lines.Add("$($p.Name) = " + (Format-IniNumber $p.Value))
        }
    }
    $lines.Add("")
}

if ($missing.Count -gt 0 -and -not $AllowMissing) {
    throw "Model files not found in $($r.ModelsDir): $($missing -join ', '). Run get-models.ps1 first (or pass -ModelsDir)."
}

$iniDir = Split-Path -Parent $ini
if ($iniDir -and -not (Test-Path $iniDir)) { New-Item -ItemType Directory -Path $iniDir -Force | Out-Null }
[System.IO.File]::WriteAllText($ini, (($lines -join "`r`n") + "`r`n"), [System.Text.Encoding]::ASCII)

# Launcher: plain cmd so TokenSaver (ai_script) and a double-click both work; it reads --port from this file.
$srv = Get-LlamaServer -LlamaDir $r.LlamaDir
$exe = if ($srv) { $srv.Exe } else { Join-Path $r.LlamaDir "llama-server.exe" }
$prefix = if ($srv -and $srv.Prefix.Count -gt 0) { ($srv.Prefix -join ' ') + ' ' } else { '' }
$apiKeyArg = if ($r.ApiKey) { " --api-key $($r.ApiKey)" } else { "" }
$modelsMax = [int](Get-Prop $settings.router 'modelsMax' 2)
$cmdLines = @(
    "@echo off",
    "title ELAI hub",
    "rem ELAI hub launcher - generated by make-preset.ps1; edit desktop\elai.json and re-run make-preset.ps1 instead of editing this file.",
    "rem llama-server router on --host $($r.Host) --port $($r.Port) (LAN + Tailscale), models from $ini",
    "rem LLAMA_CACHE: models downloaded with -hf (HF cache layout) show up in the router too, loadable on demand",
    "set LLAMA_CACHE=$($r.ModelsDir)",
    "cd /d `"$($r.LlamaDir)`"",
    "`"$exe`" $prefix--models-preset `"$ini`" --models-max $modelsMax --host $($r.Host) --port $($r.Port) --metrics$apiKeyArg",
    "if errorlevel 1 pause"
)
$cmdDir = Split-Path -Parent $cmd
if ($cmdDir -and -not (Test-Path $cmdDir)) { New-Item -ItemType Directory -Path $cmdDir -Force | Out-Null }
[System.IO.File]::WriteAllText($cmd, (($cmdLines -join "`r`n") + "`r`n"), [System.Text.Encoding]::ASCII)

if (-not $Quiet) {
    Write-Step "Wrote $ini"
    Write-Step "Wrote $cmd"
    if ($missing.Count -gt 0) { Write-Warn "missing model files: $($missing -join ', ')" }
}
